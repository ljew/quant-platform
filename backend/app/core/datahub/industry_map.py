def to_sw_l1(name: str | None) -> str:
    """东财细分行业名 → 申万一级。空值返回 "NA"，未收录返回 "其他"。"""
    if not name:
        return NA
    key = str(name).strip()
    return _MAP.get(key, OTHER)


def coverage_report(values: list[str | None]) -> dict[str, int]:
    """统计一批行业名里有多少落在映射表内（启动时自检用，便于发现新出现的行业名）。"""
    hit = miss = empty = 0
    for v in values:
        if not v:
            empty += 1
        elif v in _MAP:
            hit += 1
        else:
            miss += 1
    return {"hit": hit, "miss": miss, "empty": empty}
